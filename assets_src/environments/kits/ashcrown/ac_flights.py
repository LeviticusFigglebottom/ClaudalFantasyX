"""Writes assets/environments/kits/ashcrown/ashcrown_flights.json: the Ashcrown kit's steep flights as lines (M3-ENV-715,
for act1-chapters' Ch5 swap and the steep-stair traversal of M3-ARC-1216).

The field controller walks floors up to 45 deg; the flying stair is 48 deg and the vein stairs 60 deg (ashcrown.md
§0.1, §2.1), so a zone can't make them walkable ramps. Each flight here is a traversal's path in the kit frame (the
kit's origin, y up, the temple's front toward +Z): its foot and head on the nosing line's centre, the landings a
metre past each end on the floor it joins, its clear width between the cheeks, its angle and riser count. Kept with
the geometry: the numbers come from ac_common and ac_temple, the code that builds the flights.

Run: python3 assets_src/environments/kits/ashcrown/ac_flights.py [--check]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(HERE))

import ac_common as ac  # noqa: E402
import ac_temple as at  # noqa: E402

OUT = ROOT / "assets" / "environments" / "kits" / "ashcrown" / "ashcrown_flights.json"
LANDING_M = 1.0  # the traversal's ends: this far past the flight on the floor it joins
CHEEK_T = 0.45  # the flying stair's cheek walls (inside the outer faces at STAIR_HALF_W)


def _r(v) -> list[float]:
    return [round(float(x), 3) for x in v]


def flights() -> list[dict]:
    out = []
    foot = (0.0, ac.FLOOR_Y, ac.STAIR_FOOT_Z)
    head = (0.0, ac.TOP_Y, ac.STAIR_TOP_Z)
    out.append({
        "id": "flying_stair", "piece": "flying_stair", "angle_deg": ac.STAIR_DEG, "risers": ac.STAIR_RISERS,
        "clear_width_m": round(2.0 * (ac.STAIR_HALF_W - CHEEK_T), 3),
        "foot": _r(foot), "head": _r(head),
        "foot_landing": _r((0.0, ac.FLOOR_Y, ac.STAIR_FOOT_Z + LANDING_M)),
        "head_landing": _r((0.0, ac.TOP_Y, ac.STAIR_TOP_Z - LANDING_M)),
        "from": "forecourt", "to": "tier6",
    })
    n = int(round(ac.TIER_H / at.VSTAIR_RISE))
    for k in range(ac.TIERS - 1):
        up, low = ac.tier(k + 1), ac.tier(k)
        z = up["front"] + at.VSTAIR_W * 0.5
        x0, x1 = at.vein_stair_x(k)
        for sx, side in ((1.0, "e"), (-1.0, "w")):
            out.append({
                "id": f"vein_stair_t{k + 1}_{side}", "piece": "ashcrown_tiers",
                "angle_deg": round(math.degrees(math.atan2(at.VSTAIR_RISE, at.VSTAIR_GOING)), 1), "risers": n,
                "clear_width_m": at.VSTAIR_W,
                "head": _r((sx * x0, up["top"], z)), "foot": _r((sx * x1, low["top"], z)),
                "head_landing": _r((sx * (x0 - LANDING_M), up["top"], up["front"] - LANDING_M)),
                "foot_landing": _r((sx * (x1 + LANDING_M), low["top"], z)),
                "from": f"tier{k}", "to": f"tier{k + 1}",
            })
    return out


def document() -> dict:
    return {
        "schema": "hymn-kit-flights/1",
        "kit": "ashcrown",
        "_about": "Generated by assets_src/environments/kits/ashcrown/ac_flights.py; do not edit by hand. Kit frame "
                  "(metres, y up, the temple's front +Z). Each flight: foot and head on the nosing line's centre, "
                  "landings past each end, clear width, angle, risers; from/to name the floors it joins (forecourt, "
                  "tier0 = the first ambulatory .. tier6 = the pavilion's).",
        "flights": flights(),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = json.dumps(document(), indent=1) + "\n"
    if args.check:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("ASHCROWN_FLIGHTS " + ("OK" if ok else "STALE"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"ASHCROWN_FLIGHTS {len(document()['flights'])} flights -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
