#!/usr/bin/env python3
"""Fetch a software-rendering stack (Mesa lavapipe + llvmpipe, Xvfb) into the private Godot
sysroot made by fetch_godot.py, so the sandbox can draw real frames without a GPU (ADR 0009).

Same technique as fetch_godot.py: resolve the dependency closure of a few Ubuntu packages
from the dist that ships our pinned Godot, unpack each .deb into the *same* sysroot (one
glibc for everything), and run through the sysroot loader. No root, nothing system-wide.

Packages: mesa-vulkan-drivers (lavapipe, Vulkan -> Forward+), libgl1-mesa-dri/libegl-mesa0/
libglx-mesa0 + glvnd (llvmpipe, OpenGL -> Compatibility), libvulkan1 (loader), xvfb +
x11-xkb-utils + xauth (virtual X display), vulkan-tools (vulkaninfo, for diagnosis).

Usage:  python3 tools/dev/fetch_godot.py && python3 tools/dev/fetch_render_deps.py
Then:   <GODOT_DEST>/godot-render [godot args...]     (starts Xvfb if $DISPLAY is unset)
        e.g. godot-render --path . --rendering-driver vulkan res://tests/screenshots/capture.tscn

The wrapper exports VK_DRIVER_FILES (a patched lavapipe ICD pointing into the sysroot),
__EGL_VENDOR_LIBRARY_DIRS, LIBGL_DRIVERS_PATH, GBM_BACKENDS_PATH, XKB_CONFIG_ROOT, XLOCALEDIR
and FONTCONFIG_FILE, so nothing is read from the host's /usr.
"""
from __future__ import annotations

import argparse
import json
import os
import stat
import subprocess
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fetch_godot  # noqa: E402  (sibling module; shares the index + closure logic)

ROOTS = [
    "mesa-vulkan-drivers",
    "libvulkan1",
    "libgl1-mesa-dri",
    "libegl-mesa0",
    "libglx-mesa0",
    "libegl1",
    "libgl1",
    "xvfb",
    "x11-xkb-utils",
    "xauth",
    "vulkan-tools",
]
MARKER = ".render-deps"


def wrapper_text(dest: Path) -> str:
    sysroot = dest / "sysroot"
    lib = sysroot / "usr" / "lib" / "x86_64-linux-gnu"
    loader = lib / "ld-linux-x86-64.so.2"
    libpath = ":".join(str(p) for p in (lib, sysroot / "lib" / "x86_64-linux-gnu", lib / "pulseaudio"))
    share = sysroot / "usr" / "share"
    return f"""#!/bin/sh
# Generated by tools/dev/fetch_render_deps.py (ADR 0009). Runs Godot 4.6.3 with Mesa software
# rendering (lavapipe for --rendering-driver vulkan, llvmpipe for opengl3) on a virtual X display.
SYSROOT="{sysroot}"
LOADER="{loader}"
LIBPATH="{libpath}"
export VK_DRIVER_FILES="{dest}/lvp_icd.json"
export VK_ICD_FILENAMES="$VK_DRIVER_FILES"
export __EGL_VENDOR_LIBRARY_DIRS="{share}/glvnd/egl_vendor.d"
export LIBGL_DRIVERS_PATH="{lib}/dri"
export GBM_BACKENDS_PATH="{lib}/gbm"
export LIBGL_ALWAYS_SOFTWARE=1
export GALLIUM_DRIVER=llvmpipe
export XKB_CONFIG_ROOT="{share}/X11/xkb"
export XLOCALEDIR="{share}/X11/locale"
export FONTCONFIG_FILE="$SYSROOT/etc/fonts/fonts.conf"
export LP_NUM_THREADS="${{LP_NUM_THREADS:-$(nproc)}}"
# Pin llvmpipe SIMD width so AVX2 and AVX-512 hosts rasterise identically (baseline stability).
export LP_NATIVE_VECTOR_WIDTH="${{LP_NATIVE_VECTOR_WIDTH:-256}}"
XVFB_PID=""
if [ -z "${{DISPLAY:-}}" ]; then
  num=99
  while [ -e "/tmp/.X11-unix/X$num" ] || [ -e "/tmp/.X$num-lock" ]; do num=$((num + 1)); done
  if command -v Xvfb > /dev/null 2>&1; then
    Xvfb ":$num" -screen 0 "${{HYMN_XVFB_SCREEN:-1920x1080x24}}" -nolisten tcp > /tmp/hymn_xvfb.log 2>&1 &
  else
    "$LOADER" --library-path "$LIBPATH" "$SYSROOT/usr/bin/Xvfb" ":$num" -xkbdir "{share}/X11/xkb" \\
      -screen 0 "${{HYMN_XVFB_SCREEN:-1920x1080x24}}" -nolisten tcp > /tmp/hymn_xvfb.log 2>&1 &
  fi
  XVFB_PID=$!
  export DISPLAY=":$num"
  i=0
  while [ ! -e "/tmp/.X11-unix/X$num" ] && [ $i -lt 100 ]; do sleep 0.1; i=$((i + 1)); done
fi
"$LOADER" --library-path "$LIBPATH" "$SYSROOT/usr/bin/godot" "$@"
status=$?
[ -n "$XVFB_PID" ] && kill "$XVFB_PID" 2> /dev/null
exit $status
"""


def patch_icd(dest: Path) -> Path:
    """Point lavapipe's ICD manifest at the sysroot copy of libvulkan_lvp.so."""
    icd_dir = dest / "sysroot" / "usr" / "share" / "vulkan" / "icd.d"
    src = next(icd_dir.glob("lvp_icd*.json"))
    data = json.loads(src.read_text(encoding="utf-8"))
    name = os.path.basename(data["ICD"]["library_path"])
    data["ICD"]["library_path"] = str(dest / "sysroot" / "usr" / "lib" / "x86_64-linux-gnu" / name)
    out = dest / "lvp_icd.json"
    out.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return out


def main() -> int:
    default = Path.home() / ".cache" / "hymn" / f"godot-{fetch_godot.PINNED_DEB}"
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", type=Path, default=default, help="the fetch_godot.py destination")
    ap.add_argument("--force", action="store_true", help="re-extract even if already fetched")
    args = ap.parse_args()
    dest: Path = args.dest
    sysroot, debs = dest / "sysroot", dest / "debs"
    if not (dest / "godot").exists():
        print(f"run tools/dev/fetch_godot.py first (no {dest / 'godot'})", file=sys.stderr)
        return 1
    if not (dest / MARKER).exists() or args.force:
        for dist in fetch_godot.DISTS:
            db = fetch_godot.load_index(dist)
            if db.get(fetch_godot.PACKAGE, {}).get("Version") == fetch_godot.PINNED_DEB:
                break
        else:
            print(f"no Ubuntu dist ships {fetch_godot.PACKAGE} {fetch_godot.PINNED_DEB}", file=sys.stderr)
            return 1
        pkgs: dict[str, dict[str, str]] = {}
        for root in ROOTS:
            pkgs.update(fetch_godot.closure(db, root))
        print(f"{dist}: {len(pkgs)} packages in the render closure")
        for f in pkgs.values():
            deb = debs / os.path.basename(f["Filename"])
            if not deb.exists():
                urllib.request.urlretrieve(fetch_godot.BASE + f["Filename"], deb)
            subprocess.run(["dpkg-deb", "-x", str(deb), str(sysroot)], check=True)
        (dest / MARKER).write_text("\n".join(sorted(f"{p} {f['Version']}" for p, f in pkgs.items())) + "\n")
    print(f"ICD: {patch_icd(dest)}")
    wrapper = dest / "godot-render"
    wrapper.write_text(wrapper_text(dest))
    wrapper.chmod(wrapper.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"wrapper: {wrapper}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
