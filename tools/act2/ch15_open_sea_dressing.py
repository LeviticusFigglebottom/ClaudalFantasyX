#!/usr/bin/env python3
"""Ch15's open sea at night: the barge, the night sea and the unlamped grade (M4-A2P-045; env-art-b).

    python3 tools/act2/ch15_open_sea_dressing.py

The spec is docs/kb/plan/act2/zones/ch15_open_sea.md. The greybox's deck (4 x 10 m, chapters' M4-C15-02 layout) is
the walk and keeps the collision; the kit's barge fits it at BARGE_SCALE as `bridal_barge_sea` (its canopy and Tobin's
bier moved forward onto the greybox's Bier block, the stern clear for Kerrid's seat), so no mark moves. Nothing else:
no land, no other boat. No warm source anywhere (colour script ch15): the moon and the sea-glow are the only light.

Writes, under game/levels/ch15/open_sea/: open_sea_dressing.json, open_sea_night_environment.tres and
open_sea_night_water_material.tres; adds the Water, Tide and Dressing nodes to the scene (once).
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "assets_src" / "environments" / "kits" / "haluna"))


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, Path(__file__).resolve().parent / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ans = _load("ch13_ansedra_dressing")
import arena_scenes as AS  # noqa: E402
import bridal_barge as bb  # noqa: E402

ZONE = ROOT / "game" / "levels" / "ch15" / "open_sea"
RES_ZONE = "res://game/levels/ch15/open_sea/"
LAYOUT = ZONE / "open_sea_layout.json"
SCENE = ZONE / "open_sea.tscn"

BARGE_SCALE = 0.65  # the kit's 16 x 7.5 m barge to the greybox's 4 x 10 m deck (rails at +-2.1, +-5.1)
BARGE_YAW = -90.0  # its bow (-X) to the greybox's bow (-Z, the `bow` mark)
WATER_Y = round(bb.WATERLINE_Y * BARGE_SCALE, 3)  # the barge's waterline at its scale
SEA_GLOW = 0.12
EBBING_DATA = "res://game/data/vfx/ebbing_ch15_open_sea.json"

WATER_NAME = "open_sea_night_water_material.tres"
ENV_NAME = "open_sea_night_environment.tres"
LUT_RES = "res://assets/environments/arenas/bridal_barge_night/lut_ch15_unlamped.png"
SKY_SHADER = "res://game/shaders/environment/env_sky_pemakar.gdshader"
SKY = {"col_zenith": "Color(0.0235, 0.051, 0.0941, 1)", "col_horizon": "Color(0.1098, 0.2275, 0.2902, 1)",
       "sky_energy": "0.6", "glow_energy": "0.0", "haze_energy": "0.25", "star_density": "0.05", "star_energy": "1.0"}
FOG = {"color": "Color(0.1098, 0.2275, 0.2902, 1)", "density": 0.004}
EXPOSURE = 1.4  # the spec says 1.10; at that the bier and the party were black from the field camera (Act I's pass-3 row 49)


def blocks() -> dict:
    g = json.loads(LAYOUT.read_text(encoding="utf-8"))
    return {b["id"]: b for b in g["blocks"]}


def barge_origin_z(b: dict) -> float:
    """The barge's origin on the deck's axis so its bier lands on the greybox's Bier block."""
    bier_local = bb.BIER_AT[0] + bb.SEA_CANOPY_SHIFT
    return round(b["Bier"]["pos"][2] - bier_local * BARGE_SCALE, 3)  # yaw -90: the barge's +X is the zone's +Z


def dressing() -> dict:
    b = blocks()
    pieces = [{"piece": "bridal_barge_sea", "at": [b["Deck"]["pos"][0], barge_origin_z(b)], "y": 0.0,
               "yaw_deg": BARGE_YAW, "scale": BARGE_SCALE}]
    looks = {slot: ans.RES_ZONE + name for slot, (name, _) in ans.LOOKS.items()}
    return {
        "schema": "ZoneKitDressing (game/levels/act1/zone_kit_dressing.gd; ADR 0200)",
        "_about": "Generated by tools/act2/ch15_open_sea_dressing.py from env-art's Haluna kit (bridal_barge.py's "
        "bridal_barge_sea, M4-A2P-045); do not edit by hand. The greybox's frame.",
        "seed": 151,
        "kit_dir": ans.KIT,
        "materials_dir": ans.KIT_MATERIALS,
        "lod1_from_m": 120.0,
        "lod_end_m": 4000.0,
        "lod_margin_m": 2.0,
        "environment": RES_ZONE + ENV_NAME,
        "time_of_day_h": 1.0,
        "greybox": {"hide_all": True, "keep": []},
        # The held dead under the barge (C3): the Ebbing's rig on this zone's data; its field plays at the `shoal`
        # mark when the reveal's cue names it (both requested of chapters, M4-A2P-105).
        "ebbing": {"data": EBBING_DATA},
        "kit_material_paths": looks,
        "pieces": pieces,
    }


def _value(v) -> str:
    if isinstance(v, str) and v.startswith("#"):
        r, g, b_ = (int(v[i:i + 2], 16) / 255.0 for i in (1, 3, 5))
        return f"Color({r:.4f}, {g:.4f}, {b_:.4f}, 1)"
    return str(v)


def water() -> str:
    m = AS.NIGHT_SEA
    lines = ['[gd_resource type="ShaderMaterial" load_steps=2 format=3]', "",
             f'[ext_resource type="Shader" path="{m["shader"]}" id="1_ocean"]', "", "[resource]",
             'resource_name = "open_sea_night_water"', "render_priority = 0", 'shader = ExtResource("1_ocean")']
    lines += [f"shader_parameter/{k} = {_value(v)}" for k, v in m["params"]]
    return "\n".join(lines) + "\n"


def environment() -> str:
    sky = "\n".join(f"shader_parameter/{k} = {v}" for k, v in SKY.items())
    return f"""[gd_resource type="Environment" load_steps=5 format=3]

[ext_resource type="Shader" path="{SKY_SHADER}" id="1_sky"]
[ext_resource type="Texture3D" path="{LUT_RES}" id="2_lut"]

[sub_resource type="ShaderMaterial" id="SkyMat"]
shader = ExtResource("1_sky")
{sky}

[sub_resource type="Sky" id="Sky"]
sky_material = SubResource("SkyMat")
radiance_size = 1

[resource]
resource_name = "open_sea_ch15_night"
background_mode = 2
sky = SubResource("Sky")
ambient_light_source = 2
ambient_light_color = Color(0.0431, 0.0863, 0.1882, 1)
ambient_light_energy = 0.15
reflected_light_source = 2
tonemap_mode = 4
tonemap_exposure = {EXPOSURE}
tonemap_agx_white = 12.0
ssr_enabled = true
ssr_max_steps = 48
ssr_fade_in = 0.2
ssr_fade_out = 2.0
glow_enabled = true
glow_intensity = 0.7
glow_bloom = 0.02
glow_hdr_threshold = 1.0
fog_enabled = true
fog_light_color = {FOG["color"]}
fog_light_energy = 0.2
fog_density = {FOG["density"]}
fog_sky_affect = 0.0
adjustment_enabled = true
adjustment_color_correction = ExtResource("2_lut")
"""


SCENE_RES = (
    '[ext_resource type="Script" path="res://game/levels/act1/zone_kit_dressing.gd" id="2_dressing"]\n'
    '[ext_resource type="Script" path="res://game/levels/ch02/haluna/weathering_tide.gd" id="3_tide"]\n'
    '[ext_resource type="Script" path="res://game/world/water/water_surface.gd" id="4_water"]\n'
    '[ext_resource type="Resource" path="res://game/world/water/lagoon_waves.tres" id="5_waves"]\n'
    f'[ext_resource type="Material" path="{RES_ZONE}{WATER_NAME}" id="6_sea"]\n')
SCENE_NODES = f"""[node name="Water" type="Node3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, {WATER_Y}, 0)
script = ExtResource("4_water")
publishes_water_level = true
sea_glow_energy = {SEA_GLOW}
wave_set = ExtResource("5_waves")
material = ExtResource("6_sea")

[node name="Tide" type="Node" parent="." node_paths=PackedStringArray("water")]
script = ExtResource("3_tide")
water_height_y = {WATER_Y}
water = NodePath("../Water")

[node name="Dressing" type="Node3D" parent="." node_paths=PackedStringArray("tide")]
script = ExtResource("2_dressing")
layout_path = "{RES_ZONE}open_sea_dressing.json"
tide = NodePath("../Tide")

"""


def wire_scene() -> None:
    text = SCENE.read_text(encoding="utf-8")
    if 'id="2_dressing"' in text:
        return
    anchor = '[ext_resource type="Script" path="res://game/levels/act1/zone_cast.gd" id="90_cast"]\n'
    cast = '[node name="Cast" type="Node" parent="."]'
    assert text.count(anchor) == 1 and text.count(cast) == 1
    SCENE.write_text(text.replace(anchor, SCENE_RES + anchor).replace(cast, SCENE_NODES + cast), encoding="utf-8")


def main() -> None:
    (ZONE / "open_sea_dressing.json").write_text(json.dumps(dressing(), indent=1) + "\n", encoding="utf-8")
    (ZONE / WATER_NAME).write_text(water(), encoding="utf-8")
    (ZONE / ENV_NAME).write_text(environment(), encoding="utf-8")
    wire_scene()


if __name__ == "__main__":
    main()
