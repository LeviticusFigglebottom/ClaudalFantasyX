#!/usr/bin/env python3
"""Ch15, the open sea at night: env-art's bridal barge (bridal_barge.py, open_sea_zones.py; M3-ENV-720) on the greybox
zone `ch15/open_sea` (M4-A2P-045; open_sea_ch15.md; ADR 0200).

The greybox keeps the gameplay (the deck, the rails, the bier, the bow's trigger); the barge is built at the greybox's
size (open_sea_zones.py), so its deck, rail and bier stand where the collision does. Nothing on it gives light (colour
script ch15: the only light the sea and the dead): the grade is the Wakefin arena's, the sea its night sea with the
sea-glow. The shoal's held dead under the water are rendering's (the held light, M4-A2P-0451).

Writes (game/levels/ch15/open_sea/): the dressing, the grade, the night sea's material, and env-art's preview
(game/levels/_tests/ch15_zones/open_sea_dressed.tscn).

    python3 tools/act2/ch15_open_sea_dressing.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KIT_SRC = ROOT / "assets_src" / "environments" / "kits" / "haluna"
sys.path.insert(0, str(KIT_SRC))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import arena_scenes as ar  # noqa: E402
import bridal_barge as bb  # noqa: E402
import ch10_fen_dressing as fen  # noqa: E402
import open_sea_zones as oz  # noqa: E402

KIT = "res://assets/environments/kits/haluna/"
ZONE = "open_sea"
ZONE_DIR = ROOT / "game" / "levels" / "ch15" / ZONE
PREVIEW = ROOT / "game" / "levels" / "_tests" / "ch15_zones"
SEED = 15
WATER_Y = bb.WATERLINE_Y
SEA_GLOW = ar.BRIDAL_ARENA["sea"]["sea_glow"]
_put = fen._put


def layout() -> dict:
    d = oz.blocks()["Deck"]
    return {
        "schema": "ZoneKitDressing (game/levels/act1/zone_kit_dressing.gd; ADR 0200)",
        "_about": "Generated by tools/act2/ch15_open_sea_dressing.py from env-art's bridal barge on ch15/open_sea's "
                  "greybox (M4-A2P-045). Do not edit by hand.",
        "seed": SEED, "kit_dir": KIT, "materials_dir": KIT + "materials/", "lod1_from_m": 60.0, "lod_end_m": 800.0,
        "lod_margin_m": 3.0, "greybox": {"hide_all": True, "keep": []},
        "environment": f"res://game/levels/ch15/{ZONE}/{ZONE}_environment.tres", "time_of_day_h": 1.0,
        # the barge's X along the zone's Z, its bow (-X) to -Z: yaw -90
        "pieces": [_put("open_sea_barge", d["pos"][0], 0.0, d["pos"][2], -90.0, lod1_from_m=200.0)],
    }


def write_water() -> None:
    m = ar.NIGHT_SEA
    lines = ['[gd_resource type="ShaderMaterial" load_steps=2 format=3]', "",
             f'[ext_resource type="Shader" path="{m["shader"]}" id="1_ocean"]', "", "[resource]",
             f'resource_name = "{m["name"].replace("arena_", "")}"', "render_priority = 0", 'shader = ExtResource("1_ocean")']
    for k, v in m["params"]:
        if isinstance(v, str) and v.startswith("#"):
            c = [int(v[i:i + 2], 16) / 255 for i in (1, 3, 5)]
            v = f"Color({c[0]:.4f}, {c[1]:.4f}, {c[2]:.4f}, 1)"
        lines.append(f"shader_parameter/{k} = {v}")
    (ZONE_DIR / f"{ZONE}_water_material.tres").write_text("\n".join(lines) + "\n", encoding="utf-8")


CAMERAS = [
    ("U01_bow_to_stern", (1.6, 1.4, -3.0), (0.0, 0.8, 4.2), 40.0),
    ("Bier_close", (-1.2, 1.3, -0.4), (0.4, 0.5, 1.5), 50.0),
    ("Kerrid_stern", (0.8, 1.5, 0.8), (0.0, 0.8, 4.6), 55.0),
    ("Bow_dark_sea", (0.0, 1.6, -2.0), (0.0, 0.0, -30.0), 55.0),
    ("Over_rail", (1.8, 1.4, 0.0), (12.0, -1.0, -6.0), 50.0),
    ("From_water", (7.0, 0.4, -6.0), (0.0, 0.6, 0.0), 45.0),
    ("Canopy_under", (0.3, 1.2, 0.6), (0.0, 2.4, 1.8), 70.0),
    ("Shoal_down", (2.0, 1.6, -3.5), (6.0, -3.0, -8.0), 55.0),
    ("Wide_high", (-10.0, 8.0, 10.0), (0.0, 0.0, 0.0), 45.0),
    ("Deck_walk", (0.0, 1.6, 3.8), (0.0, 1.0, -5.0), 60.0),
]


def write_preview() -> Path:
    lines = ["[gd_scene format=3]", "",
             '[ext_resource type="Script" path="res://game/levels/ch15/ch15_zone.gd" id="1_zone"]',
             '[ext_resource type="Script" path="res://game/levels/act1/zone_kit_dressing.gd" id="2_dressing"]',
             '[ext_resource type="Script" path="res://game/levels/ch02/haluna/weathering_tide.gd" id="3_tide"]',
             '[ext_resource type="Script" path="res://game/world/water/water_surface.gd" id="4_water"]',
             '[ext_resource type="Resource" path="res://game/world/water/lagoon_waves.tres" id="5_waves"]',
             f'[ext_resource type="Material" path="res://game/levels/ch15/{ZONE}/{ZONE}_water_material.tres" id="6_mat"]',
             '[ext_resource type="Script" path="res://game/levels/act1/zone_cast.gd" id="7_cast"]', "",
             '[node name="OpenSea" type="Node3D"]', 'script = ExtResource("1_zone")', f'location_id = &"ch15/{ZONE}"',
             f'layout_path = "res://game/levels/ch15/{ZONE}/{ZONE}_layout.json"', "",
             '[node name="Cast" type="Node" parent="."]', 'script = ExtResource("7_cast")', "",
             '[node name="Water" type="Node3D" parent="."]',
             f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, {WATER_Y}, 0)", 'script = ExtResource("4_water")',
             "publishes_water_level = true", 'wave_set = ExtResource("5_waves")', 'material = ExtResource("6_mat")',
             f"sea_glow_energy = {SEA_GLOW}", "",
             '[node name="Tide" type="Node" parent="." node_paths=PackedStringArray("water")]',
             'script = ExtResource("3_tide")', f"tide_line_y = {WATER_Y}", f"water_height_y = {WATER_Y}",
             'water = NodePath("../Water")', "",
             '[node name="Dressing" type="Node3D" parent="." node_paths=PackedStringArray("tide")]',
             'script = ExtResource("2_dressing")', f'layout_path = "res://game/levels/ch15/{ZONE}/{ZONE}_dressing.json"',
             'tide = NodePath("../Tide")', "", '[node name="Cameras" type="Node3D" parent="."]', ""]
    for name, pos, look, fov in CAMERAS:
        lines += [f'[node name="{name}" type="Camera3D" parent="Cameras"]', f"fov = {fov}", "near = 0.1", "far = 2500.0",
                  f"transform = {fen._look_xform(pos, look)}", ""]
    out = PREVIEW / f"{ZONE}_dressed.tscn"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    return out


def main() -> int:
    ar.write_environment(dict(ar.BRIDAL_ARENA), ZONE_DIR / f"{ZONE}_environment.tres")
    write_water()
    lay = layout()
    (ZONE_DIR / f"{ZONE}_dressing.json").write_text(json.dumps(lay, indent=1) + "\n", encoding="utf-8")
    write_preview()
    print(f"DRESSING {ZONE}: {len(lay['pieces'])} pieces")
    return 0


if __name__ == "__main__":
    sys.exit(main())
