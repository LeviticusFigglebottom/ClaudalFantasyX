#!/usr/bin/env python3
"""The Lamp Archive's dressing (M4-A2P-043; env-art-b).

    python3 tools/act2/ch13_archive_dressing.py

The spec is docs/kb/plan/act2/zones/ch13_lamp_archive.md. Dressed in the greybox's own frame (chapters' M4-C13-02
layout): a ledger case stands on every Stack block, the tables on theirs, and the room's walls and floor on the
greybox's, so the greybox keeps the collision and no story point moves. The light is the city's grey daylight through
the clerestories (Ansedra's grade and `lut_ch13_still`); no lamp is lit. The room takes a copy of Ansedra's grade
with dust in the air and less sky fill (env-art-b's Act II beauty pass), so the daylight falls in the spec's shafts.

Writes game/levels/ch13/lamp_archive/lamp_archive_dressing.json; reuses Ansedra's looks and grade; adds the Dressing
node to lamp_archive.tscn (once).
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, Path(__file__).resolve().parent / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ans = _load("ch13_ansedra_dressing")

ZONE = ROOT / "game" / "levels" / "ch13" / "lamp_archive"
RES_ZONE = "res://game/levels/ch13/lamp_archive/"
LAYOUT = ZONE / "lamp_archive_layout.json"
SCENE = ZONE / "lamp_archive.tscn"

HALL_BAYS = 5
HALL_BAY_M = 6.4
TABLES = {"LedgerTable": "reading_table", "RollTable": "roll_table"}
# The days' work on the floor, in the alcoves between the cases (off the aisle the story walks).
LEDGER_STACKS = ((-8.5, -8.7, 20.0), (8.3, -14.2, 75.0), (-8.2, -19.8, 140.0), (8.6, -25.2, 300.0))


# The beauty pass (10-30): under Ansedra's open-air grade the room read as one flat grey wash, no shaft in it. Less
# ambient (the vault is lit by its windows, not the sky) and a dusty volumetric fog that scatters forward, so the
# clerestories' light hangs in the aisles as shafts.
ENV_NAME = "lamp_archive_environment.tres"
ENV_SET = {"ambient_light_energy": "0.28", "tonemap_exposure": "0.85"}
ENV_ADD = {"volumetric_fog_enabled": "true", "volumetric_fog_density": "0.045",
           "volumetric_fog_albedo": "Color(0.86, 0.84, 0.8, 1)", "volumetric_fog_anisotropy": "0.55",
           "volumetric_fog_length": "48.0", "volumetric_fog_ambient_inject": "0.15", "volumetric_fog_sky_affect": "0.0"}


# The PC's row 86 (Act II first look): from the Door spawn the field camera looks down on the floor, and Ansedra's
# white-painted marble (paint_cover 0.9) read there as one plain grey slab, greybox-like. The reading room's own copy
# lets the stone through the paint, warmer, with its joints and a little relief, so the floor reads as worn
# flagstones under the daylight.
MARBLE_NAME = "lamp_archive_marble_material.tres"
MARBLE_OVERRIDES = {"col_paint": "Color(0.78, 0.75, 0.7, 1)", "paint_cover": "0.55", "cavity_darken": "0.35",
                    "normal_strength": "0.6", "roughness_base": "0.5", "specular_base": "0.35"}


def environment() -> str:
    """Ansedra's grade with ENV_SET replaced and ENV_ADD appended."""
    text = (ROOT / (ans.RES_ZONE + ans.ENV_NAME).removeprefix("res://")).read_text(encoding="utf-8")
    text = text.replace('resource_name = "ansedra_ch13"', 'resource_name = "lamp_archive_ch13"')
    for key, value in ENV_SET.items():
        line = f"{key} = "
        assert text.count("\n" + line) == 1, key
        start = text.index("\n" + line) + 1
        text = text[:start] + line + value + text[text.index("\n", start):]
    for key, value in ENV_ADD.items():
        assert ("\n" + key + " = ") not in text, key
    return text.rstrip("\n") + "\n" + "".join(f"{k} = {v}\n" for k, v in ENV_ADD.items())


def blocks() -> dict:
    g = json.loads(LAYOUT.read_text(encoding="utf-8"))
    return {b["id"]: b for b in g["blocks"]}


def dressing() -> dict:
    b = blocks()
    pieces = [{"piece": "archive_end_walls", "at": [0.0, 0.0], "y": 0.0, "yaw_deg": 0.0}]
    pieces += [{"piece": "archive_hall_bay", "at": [0.0, round(-HALL_BAY_M * (k + 0.5), 3)], "y": 0.0, "yaw_deg": 0.0}
               for k in range(HALL_BAYS)]
    pieces += [{"piece": "archive_case", "at": [v["pos"][0], v["pos"][2]], "y": 0.0, "yaw_deg": 0.0}
               for k, v in sorted(b.items()) if k.startswith("Stack")]
    pieces += [{"piece": piece, "at": [b[bid]["pos"][0], b[bid]["pos"][2]], "y": 0.0, "yaw_deg": 0.0}
               for bid, piece in TABLES.items()]
    pieces += [{"piece": "ledger_stack", "at": [x, z], "y": 0.0, "yaw_deg": yaw} for x, z, yaw in LEDGER_STACKS]
    looks = {slot: ans.RES_ZONE + name for slot, (name, _) in ans.LOOKS.items()}
    looks["kit_order_marble"] = RES_ZONE + MARBLE_NAME
    return {
        "schema": "ZoneKitDressing (game/levels/act1/zone_kit_dressing.gd; ADR 0200)",
        "_about": "Generated by tools/act2/ch13_archive_dressing.py from env-art's Haluna kit (ansedra.py's Archive "
        "pieces, M4-A2P-043); do not edit by hand. The greybox's frame.",
        "seed": 132,
        "kit_dir": ans.KIT,
        "materials_dir": ans.KIT_MATERIALS,
        "lod1_from_m": 120.0,
        "lod_end_m": 4000.0,
        "lod_margin_m": 2.0,
        "environment": RES_ZONE + ENV_NAME,
        "time_of_day_h": 16.5,
        "greybox": {"hide_all": True, "keep": []},
        "kit_material_paths": looks,
        "pieces": pieces,
    }


SCENE_RES = '[ext_resource type="Script" path="res://game/levels/act1/zone_kit_dressing.gd" id="2_dressing"]\n'
SCENE_NODE = f"""[node name="Dressing" type="Node3D" parent="."]
script = ExtResource("2_dressing")
layout_path = "{RES_ZONE}lamp_archive_dressing.json"

"""


def wire_scene() -> None:
    text = SCENE.read_text(encoding="utf-8")
    if 'id="2_dressing"' in text:
        return
    anchor = '[ext_resource type="Script" path="res://game/levels/act1/zone_cast.gd" id="90_cast"]\n'
    cast = '[node name="Cast" type="Node" parent="."]'
    assert text.count(anchor) == 1 and text.count(cast) == 1
    SCENE.write_text(text.replace(anchor, SCENE_RES + anchor).replace(cast, SCENE_NODE + cast), encoding="utf-8")


def main() -> None:
    (ZONE / "lamp_archive_dressing.json").write_text(json.dumps(dressing(), indent=1) + "\n", encoding="utf-8")
    (ZONE / ENV_NAME).write_text(environment(), encoding="utf-8")
    (ZONE / MARBLE_NAME).write_text(ans.zl.copy_material(ans.KIT_MATERIALS + "kit_order_marble.tres",
                                                         MARBLE_NAME.removesuffix(".tres"), MARBLE_OVERRIDES),
                                    encoding="utf-8")
    wire_scene()


if __name__ == "__main__":
    main()
