#!/usr/bin/env python3
"""Ch14, the Peace Wedding: env-art's Ansedra kit (ansedra.py, bridal_barge.py, ansedra_zones.py; M3-ENV-720/721) on the
greybox zone `ch13/ansedra_lacquer_court` (M4-A2P-044; ansedra.md; ADR 0200).

The greybox keeps the gameplay: the court, its columns, galleries, dais, the water-steps, the barge and the gate stay as
they are and only their look is swapped (ansedra_zones.build_court, from the same greybox). Round it: the red-lacquer
halls on three sides of the court, the bridal barge on its block, and across the lagoon the city at its windows
(`bowl_dome_lit` on their islands, the far skyline lit) for the bells.

The greybox's barge deck stands at -0.6 under its Water block's -0.3; the zone's water goes to -0.95, under the deck, the
water-steps going down to it (M4-A2P-0441 asks chapters to match the Water block).

Writes (game/levels/ch13/ansedra_lacquer_court/): the dressing, the grade (colour script ch14, lut_ch14_wedding, the
arena's dusk), the water (the lacquer lagoon, still) and env-art's preview (game/levels/_tests/ch14_zones/).

    python3 tools/act2/ch14_court_dressing.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KIT_SRC = ROOT / "assets_src" / "environments" / "kits" / "haluna"
sys.path.insert(0, str(KIT_SRC))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import arena_scenes as ar  # noqa: E402
import bridal_barge as bb  # noqa: E402
import ch10_fen_dressing as fen  # noqa: E402
import ansedra_zones as az  # noqa: E402
import ch11_lowlight_dressing as low  # noqa: E402

KIT = "res://assets/environments/kits/haluna/"
ZONE = "ansedra_lacquer_court"
ZONE_DIR = ROOT / "game" / "levels" / "ch13" / ZONE
PREVIEW = ROOT / "game" / "levels" / "_tests" / "ch14_zones"
SEED = 14
NEVER_LOD_M = 5000.0
WATER_Y = -0.95
BARGE_SCALE = 0.53
LANTERN_COLOR = "#FFB16E"  # palette oil_lamp  # the arena's 16 x 7.5 m barge on the greybox's 10 x 4 m block
r3 = fen.r3
_put = fen._put

# Red-lacquer halls on three sides of the court (W01), fronts toward it: (x, z, yaw).
HALLS = [(-8.0, -24.6, 0.0), (8.0, -24.6, 0.0), (-15.6, -6.0, 90.0), (-15.6, -18.0, 90.0), (15.6, -10.0, -90.0),
         (15.6, -22.0, -90.0)]
# The city across the lagoon, at its windows for the bells: (x, z, scale).
CITY_DOMES = [(-24.0, 22.0, 1.2), (20.0, 26.0, 1.4), (-45.0, 8.0, 1.6), (44.0, 6.0, 1.5), (-8.0, 46.0, 1.8),
              (30.0, 48.0, 1.6), (-38.0, 40.0, 1.4), (58.0, 30.0, 1.7), (-60.0, -20.0, 1.5), (60.0, -30.0, 1.6)]


def _layout() -> dict:
    return json.loads((ZONE_DIR / f"{ZONE}_layout.json").read_text(encoding="utf-8"))


def layout() -> dict:
    bl = {b["id"]: b for b in _layout()["blocks"]}
    b = bl["Barge"]
    deck_y = b["pos"][1] + b["size"][1] / 2
    mid_x = (bb.BOW_X + bb.STERN_X) / 2 * BARGE_SCALE
    pieces = [_put("ansedra_court", 0.0, 0.0, 0.0, 0.0, lod1_from_m=NEVER_LOD_M),
              # the bridal barge, its bow (-X) to the gate (+Z), its deck on the block's top
              _put("bridal_barge", b["pos"][0], deck_y, b["pos"][2] + mid_x, 90.0, scale=BARGE_SCALE)]
    pieces += [_put("lacquer_hall", x, 0.0, z, yaw) for x, z, yaw in HALLS]
    pieces += [_put("bowl_dome_lit", x, WATER_Y, z, (k * 41.0) % 360.0, scale=s) for k, (x, z, s) in enumerate(CITY_DOMES)]
    pieces.append(_put("ansedra_far_domes_lit", 0.0, WATER_Y, 0.0, 0.0, lod1_from_m=1200.0))
    return {
        "schema": "ZoneKitDressing (game/levels/act1/zone_kit_dressing.gd; ADR 0200)",
        "_about": f"Generated by tools/act2/ch14_court_dressing.py from env-art's Ansedra kit on ch13/{ZONE}'s greybox "
                  "(M4-A2P-044). Do not edit by hand.",
        "seed": SEED, "kit_dir": KIT, "materials_dir": KIT + "materials/", "lod1_from_m": 70.0, "lod_end_m": 1500.0,
        "lod_margin_m": 3.0, "greybox": {"hide_all": True, "keep": []},
        "environment": f"res://game/levels/ch13/{ZONE}/{ZONE}_environment.tres", "time_of_day_h": 18.5,
        "pieces": pieces,
        # The wedding's lanterns under the colonnade (warm oil-lamp light; the barges carry none), shadowless.
        "fire_light_color": LANTERN_COLOR,
        "fire_lights": [{"at": list(p), "energy": 1.1, "range": 7.0} for p in az.lantern_points(_layout())],
    }


def write_water() -> None:
    m = ar.LACQUER_LAGOON
    lines = ['[gd_resource type="ShaderMaterial" load_steps=2 format=3]', "",
             f'[ext_resource type="Shader" path="{m["shader"]}" id="1_ocean"]', "", "[resource]",
             f'resource_name = "{m["name"].replace("arena_", "")}"', "render_priority = 0", 'shader = ExtResource("1_ocean")']
    over = {"detail_strength": 0.05, "foam_crest_threshold": 0.15}
    for k, v in [(k, over.get(k, v)) for k, v in m["params"]] + [(k, v) for k, v in over.items()
                                                                  if k not in dict(m["params"])]:
        if isinstance(v, str) and v.startswith("#"):
            c = [int(v[i:i + 2], 16) / 255 for i in (1, 3, 5)]
            v = f"Color({c[0]:.4f}, {c[1]:.4f}, {c[2]:.4f}, 1)"
        lines.append(f"shader_parameter/{k} = {v}")
    (ZONE_DIR / f"{ZONE}_water_material.tres").write_text("\n".join(lines) + "\n", encoding="utf-8")
    saved = ar.LOWLIGHT_ARENA["sea"]["waves"]
    try:
        ar.LOWLIGHT_ARENA["sea"]["waves"] = [(200.0, 4.0, 0.002, 0.05)]  # still, until the escape's first ripple
        low.write_waves(ZONE_DIR / f"{ZONE}_waves.tres")
    finally:
        ar.LOWLIGHT_ARENA["sea"]["waves"] = saved


CAMERAS = [
    ("W01_court", (0.0, 2.4, -2.0), (0.0, 1.4, -21.0), 45.0),
    ("Entry_east", (16.0, 1.7, -2.5), (-4.0, 2.5, -14.0), 55.0),
    ("Dais_vows", (0.0, 1.6, -15.0), (0.0, 1.2, -21.5), 50.0),
    ("Conclave_gallery", (-4.0, 1.7, -14.0), (-12.0, 2.4, -21.5), 55.0),
    ("Colonnade_west", (-9.0, 1.7, -3.0), (-14.0, 4.0, -18.0), 60.0),
    ("Water_steps", (0.0, 1.7, -4.0), (0.0, -0.4, 10.0), 55.0),
    ("Barge_from_steps", (1.5, 1.6, 0.5), (0.0, -0.4, 14.0), 55.0),
    ("Gate_from_barge", (0.0, 0.8, 7.0), (0.0, 3.0, 18.0), 60.0),
    ("Lagoon_city", (0.0, 1.0, 14.0), (0.0, 4.0, 60.0), 50.0),
    ("Over_court", (22.0, 18.0, 10.0), (0.0, 0.0, -12.0), 55.0),
]


def write_preview() -> Path:
    lines = ["[gd_scene format=3]", "",
             '[ext_resource type="Script" path="res://game/levels/ch13/ch13_zone.gd" id="1_zone"]',
             '[ext_resource type="Script" path="res://game/levels/act1/zone_kit_dressing.gd" id="2_dressing"]',
             '[ext_resource type="Script" path="res://game/levels/ch02/haluna/weathering_tide.gd" id="3_tide"]',
             '[ext_resource type="Script" path="res://game/world/water/water_surface.gd" id="4_water"]',
             f'[ext_resource type="Resource" path="res://game/levels/ch13/{ZONE}/{ZONE}_waves.tres" id="5_waves"]',
             f'[ext_resource type="Material" path="res://game/levels/ch13/{ZONE}/{ZONE}_water_material.tres" id="6_mat"]',
             '[ext_resource type="Script" path="res://game/levels/act1/zone_cast.gd" id="7_cast"]', "",
             '[node name="AnsedraLacquerCourt" type="Node3D"]', 'script = ExtResource("1_zone")',
             f'location_id = &"ch13/{ZONE}"', f'layout_path = "res://game/levels/ch13/{ZONE}/{ZONE}_layout.json"', "",
             '[node name="Cast" type="Node" parent="."]', 'script = ExtResource("7_cast")', "",
             '[node name="Water" type="Node3D" parent="."]',
             f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, {WATER_Y}, 0)", 'script = ExtResource("4_water")',
             "publishes_water_level = true", 'wave_set = ExtResource("5_waves")', 'material = ExtResource("6_mat")', "",
             '[node name="Tide" type="Node" parent="." node_paths=PackedStringArray("water")]',
             'script = ExtResource("3_tide")', f"tide_line_y = {WATER_Y}", f"water_height_y = {WATER_Y}",
             'water = NodePath("../Water")', "",
             '[node name="Dressing" type="Node3D" parent="." node_paths=PackedStringArray("tide")]',
             'script = ExtResource("2_dressing")', f'layout_path = "res://game/levels/ch13/{ZONE}/{ZONE}_dressing.json"',
             'tide = NodePath("../Tide")', "", '[node name="Cameras" type="Node3D" parent="."]', ""]
    for name, pos, look, fov in CAMERAS:
        lines += [f'[node name="{name}" type="Camera3D" parent="Cameras"]', f"fov = {fov}", "near = 0.1", "far = 2500.0",
                  f"transform = {fen._look_xform(pos, look)}", ""]
    out = PREVIEW / f"{ZONE}_dressed.tscn"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    return out


def main() -> int:
    ar.write_environment(dict(ar.ANSEDRA_ESCAPE), ZONE_DIR / f"{ZONE}_environment.tres")
    write_water()
    lay = layout()
    (ZONE_DIR / f"{ZONE}_dressing.json").write_text(json.dumps(lay, indent=1) + "\n", encoding="utf-8")
    write_preview()
    print(f"DRESSING {ZONE}: {len(lay['pieces'])} pieces")
    return 0


if __name__ == "__main__":
    sys.exit(main())
