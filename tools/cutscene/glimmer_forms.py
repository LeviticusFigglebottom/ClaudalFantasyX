#!/usr/bin/env python3
"""M2-FP-120: the bound light's forms for `@vfx glimmer_bound form=<id>` (color_script.md S08: "Ilun's form holds
still in a held frame").

A form is GlimmerField.MAX_SPAWN_POINTS (16) points spread over a creature's rest-pose mesh: farthest-point sampling
over every vertex, starting from the vertex farthest from the mesh's centre, so the points mark its outline (wing
tips, head, tail) before its body. Points are centred on the mesh's bounding-box centre, so the form stands on the
cue's `at=` place. Writes game/data/cutscene/glimmer_forms.json; --check fails when it is stale.

    python3 tools/cutscene/glimmer_forms.py [--check]
"""
from __future__ import annotations

import argparse
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "game/data/cutscene/glimmer_forms.json"
POINTS = 16  # GlimmerField.MAX_SPAWN_POINTS (glimmer_motes_process.gdshader HYMN_GLIMMER_MAX_SPAWN_POINTS)
DECIMALS = 3
# form id -> the creature model whose rest pose it takes (Vowbound forms: palette.json 0.1.1)
FORMS = {"ilun": "assets/creatures/ilun/ilun.glb"}
COMPONENT_SIZE = {5126: 4}
TYPE_WIDTH = {"VEC3": 3}


def glb_positions(path: Path) -> list[tuple[float, float, float]]:
    """Every POSITION vertex of every primitive in the GLB's binary chunk (rest pose, mesh space)."""
    data = path.read_bytes()
    json_len = struct.unpack_from("<I", data, 12)[0]
    doc = json.loads(data[20:20 + json_len])
    bin_start = 20 + json_len + 8
    out: list[tuple[float, float, float]] = []
    for mesh in doc["meshes"]:
        for prim in mesh["primitives"]:
            acc = doc["accessors"][prim["attributes"]["POSITION"]]
            view = doc["bufferViews"][acc["bufferView"]]
            stride = view.get("byteStride", COMPONENT_SIZE[acc["componentType"]] * TYPE_WIDTH[acc["type"]])
            base = bin_start + view.get("byteOffset", 0) + acc.get("byteOffset", 0)
            for i in range(acc["count"]):
                out.append(struct.unpack_from("<fff", data, base + i * stride))
    return out


def sample(points: list[tuple[float, float, float]], n: int) -> list[list[float]]:
    lo = [min(p[k] for p in points) for k in range(3)]
    hi = [max(p[k] for p in points) for k in range(3)]
    centre = [(lo[k] + hi[k]) * 0.5 for k in range(3)]
    pts = [tuple(p[k] - centre[k] for k in range(3)) for p in points]

    def d2(a, b):
        return sum((a[k] - b[k]) ** 2 for k in range(3))

    first = max(range(len(pts)), key=lambda i: (d2(pts[i], (0.0, 0.0, 0.0)), -i))
    chosen = [first]
    near = [d2(p, pts[first]) for p in pts]
    while len(chosen) < n:
        nxt = max(range(len(pts)), key=lambda i: (near[i], -i))
        chosen.append(nxt)
        near = [min(near[i], d2(pts[i], pts[nxt])) for i in range(len(pts))]
    return [[round(c, DECIMALS) for c in pts[i]] for i in chosen]


def build() -> dict:
    forms = {}
    for form_id, rel in sorted(FORMS.items()):
        forms[form_id] = {"model": rel, "points": sample(glb_positions(ROOT / rel), POINTS)}
    return {
        "_doc": "Generated by tools/cutscene/glimmer_forms.py (M2-FP-120); do not edit. `@vfx glimmer_bound form=<id>`: "
        "the bound field's motes stand still on these points (GlimmerField.spawn_points, local to the cue's place), "
        "one mote each, outlining the creature's rest pose.",
        "forms": forms,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = json.dumps(build(), indent=1) + "\n"
    if ap.parse_args().check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/cutscene/glimmer_forms.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
