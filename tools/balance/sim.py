#!/usr/bin/env python3
"""Balancing simulator front end (M1-CMB-05, SPEC §6.9).

Runs game/battle/sim/sim_main.gd in headless Godot for every suite in
tools/balance/targets.json, checks each policy's win rate against its band, and writes:

  * docs/kb/design/balance_report.md: a Markdown summary table. Everything below the
    "<!-- tuning-log -->" marker is kept as is, so hand-written tuning notes survive reruns.
  * tools/balance/out/balance_runs.csv: one row per seeded battle (gitignored).
  * tools/balance/out/balance_summary.csv: one row per suite and policy (gitignored).

Suites whose encounter is not authored yet are listed as pending, not failed.

Usage: python3 tools/balance/sim.py [--seeds N] [--suite ID ...] [--godot PATH]
                                    [--report PATH] [--out-dir PATH] [--check]
--check exits 1 if any band is missed (for local gating; CI does not run it yet).
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGETS = ROOT / "tools/balance/targets.json"
ENCOUNTERS = ROOT / "game/data/battle/encounters.json"
REPORT = ROOT / "docs/kb/design/balance_report.md"
OUT_DIR = ROOT / "tools/balance/out"
SIM_SCRIPT = "res://game/battle/sim/sim_main.gd"
PREFIX = "SIM_RESULT "
LOG_MARKER = "<!-- tuning-log -->"
DEFAULT_SEEDS = 1000
RUN_FIELDS = ["suite", "encounter", "policy", "seed", "outcome", "turns", "party_turns", "party_ko", "items"]
SUMMARY_FIELDS = ["suite", "chapter", "encounter", "policy", "n", "wins", "win_pct", "band", "in_band",
                  "timeouts", "mean_turns", "p90_turns", "mean_party_ko", "mean_items"]


def load_targets(path: Path = TARGETS) -> list[dict]:
    return json.loads(path.read_text())["suites"]


def authored_encounters(path: Path = ENCOUNTERS) -> set[str]:
    return {e["id"] for e in json.loads(path.read_text())["encounters"]}


def run_suite(godot: str, suite: dict, seeds: int) -> list[dict]:
    """Runs one suite in Godot and returns its aggregates (each with a "runs" list)."""
    policies = ",".join(suite["bands"].keys())
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "sim.json"
        cmd = [godot, "--headless", "--path", str(ROOT), "-s", SIM_SCRIPT, "--",
               f"--encounter={suite['encounter']}", f"--active={','.join(suite['active'])}",
               f"--reserve={','.join(suite['reserve'])}", f"--policies={policies}",
               f"--seeds={seeds}", f"--out={out}"]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=3600)
        if proc.returncode != 0 or not out.exists():
            sys.stderr.write(proc.stdout + proc.stderr)
            raise RuntimeError(f"sim failed for suite {suite['id']} (exit {proc.returncode})")
        return json.loads(out.read_text())


def in_band(win_pct: float, band: list[int] | None) -> bool:
    return band is None or band[0] <= win_pct <= band[1]


def band_text(band: list[int] | None) -> str:
    return "report only" if band is None else f"{band[0]}–{band[1]}%"


def summary_rows(suite: dict, results: list[dict]) -> list[dict]:
    rows = []
    for r in results:
        band = suite["bands"][r["policy"]]
        rows.append({
            "suite": suite["id"], "chapter": suite["chapter"], "encounter": suite["encounter"],
            "policy": r["policy"], "n": r["n"], "wins": r["wins"], "win_pct": round(r["win_pct"], 1),
            "band": band_text(band),
            "in_band": (in_band(r["win_pct"], band) and r["timeouts"] == 0
                        and r["p90_turns"] <= suite.get("p90_turns_max", r["p90_turns"])),
            "timeouts": r["timeouts"], "mean_turns": round(r["mean_turns"], 1), "p90_turns": r["p90_turns"],
            "mean_party_ko": round(r["mean_party_ko"], 2), "mean_items": round(r["mean_items"], 2),
        })
    return rows


def markdown(rows: list[dict], pending: list[dict], seeds: int, today: str) -> str:
    lines = [
        "# Balance Report",
        "",
        f"Generated by `python3 tools/balance/sim.py` on {today}, {seeds} seeds per policy "
        "(seeds 1..N). Targets and policy definitions: [balance_targets.md](balance_targets.md). "
        "Per-seed CSVs go to `tools/balance/out/` (gitignored).",
        "",
        "`turns` counts every action by both sides (automatic Berserk/Confuse turns included, "
        "turns lost to Stop/Sleep excluded). `party KO` is the mean number of party members "
        "down (KO or stone) at the end. Items don't exist yet, so `items` is always 0 (hook in `SimPolicy.items_used`).",
        "",
        "| Chapter | Encounter | Policy | Win % | Band | OK | Mean turns | p90 turns | Party KO | Items |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        ok = "yes" if r["in_band"] else "**NO**"
        lines.append(f"| {r['chapter']} | `{r['encounter']}` | {r['policy']} | {r['win_pct']:.1f} | {r['band']} | "
                     f"{ok} | {r['mean_turns']:.1f} | {r['p90_turns']} | {r['mean_party_ko']:.2f} | "
                     f"{r['mean_items']:.2f} |")
    for s in pending:
        lines.append(f"| {s['chapter']} | `{s['encounter']}` | (all) | pending | see targets | n/a | | | | |")
    if pending:
        lines += ["", "Pending suites have target bands but no encounter data yet: "
                  + ", ".join(f"`{s['encounter']}`" for s in pending) + "."]
    return "\n".join(lines) + "\n"


def write_report(path: Path, body: str) -> None:
    tail = ""
    if path.exists():
        old = path.read_text()
        if LOG_MARKER in old:
            tail = old[old.index(LOG_MARKER):]
    if not tail:
        tail = LOG_MARKER + "\n\n## Tuning log\n\n(Hand-written notes go below this marker; reruns keep them.)\n"
    path.write_text(body + "\n" + tail)


def write_csv(path: Path, fields: list[str], rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=DEFAULT_SEEDS)
    ap.add_argument("--suite", action="append", help="suite id(s) from targets.json (default: all)")
    ap.add_argument("--godot", default=os.environ.get("GODOT", "godot"))
    ap.add_argument("--report", type=Path, default=REPORT)
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    ap.add_argument("--check", action="store_true", help="exit 1 if a band is missed")
    args = ap.parse_args(argv)

    suites = [s for s in load_targets() if not args.suite or s["id"] in args.suite]
    authored = authored_encounters()
    rows: list[dict] = []
    runs: list[dict] = []
    pending: list[dict] = []
    for suite in suites:
        if suite["encounter"] not in authored:
            pending.append(suite)
            print(f"{suite['id']}: encounter '{suite['encounter']}' not authored yet (pending)")
            continue
        results = run_suite(args.godot, suite, args.seeds)
        for r in results:
            for run in r["runs"]:
                runs.append({"suite": suite["id"], "encounter": suite["encounter"], "policy": r["policy"], **run})
        for row in summary_rows(suite, results):
            rows.append(row)
            flag = "ok" if row["in_band"] else "OUT OF BAND"
            print(f"{suite['id']:>14} {row['policy']:>12}: {row['win_pct']:5.1f}% (band {row['band']}) {flag}")
    write_csv(args.out_dir / "balance_runs.csv", RUN_FIELDS, runs)
    write_csv(args.out_dir / "balance_summary.csv", SUMMARY_FIELDS, rows)
    write_report(args.report, markdown(rows, pending, args.seeds, dt.date.today().isoformat()))
    print(f"wrote {args.report.relative_to(ROOT) if args.report.is_relative_to(ROOT) else args.report}")
    missed = [r for r in rows if not r["in_band"]]
    return 1 if args.check and missed else 0


if __name__ == "__main__":
    sys.exit(main())
